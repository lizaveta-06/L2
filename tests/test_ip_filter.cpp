#include "ip_filter.h"

#include <gtest/gtest.h>

// ============================================================
// Тест 1. split — разбиение строки по разделителю
// ============================================================
TEST(SplitTest, BasicSplit)
{
    auto r = split("11.22.33.44", '.');
    ASSERT_EQ(r.size(), 4u);
    EXPECT_EQ(r[0], "11");
    EXPECT_EQ(r[1], "22");
    EXPECT_EQ(r[2], "33");
    EXPECT_EQ(r[3], "44");
}

// ============================================================
// Тест 2. sort_ips — обратная лексикографическая сортировка
// ============================================================
TEST(SortTest, ReverseLexicographicByBytes)
{
    // 1.10.1.1 > 1.2.1.1 (10 > 2), поэтому 1.10.1.1 идёт первым
    std::vector<std::vector<std::string>> pool = {
        {"1", "1", "1", "1"},
        {"1", "10", "1", "1"},
        {"1", "2", "1", "1"},
    };

    sort_ips(pool);

    EXPECT_EQ(pool[0][1], "10");
    EXPECT_EQ(pool[1][1], "2");
    EXPECT_EQ(pool[2][1], "1");
}

// ============================================================
// Тест 3. filter_by_any_byte — фильтр по любому байту
// ============================================================
TEST(FilterTest, AnyByteEquals46)
{
    std::vector<std::vector<std::string>> pool = {
        {"186", "204", "34", "46"}, // 46 в 4-м байте
        {"186", "46", "222", "194"}, // 46 во 2-м байте
        {"1", "1", "1", "1"},        // нет 46
        {"46", "70", "225", "39"},   // 46 в 1-м байте
    };

    auto r = filter_by_any_byte(pool, 46);
    ASSERT_EQ(r.size(), 3u);
}